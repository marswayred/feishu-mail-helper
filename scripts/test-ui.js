import { createServer } from 'node:http';
import { once } from 'node:events';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createApp, loadConfig } from '../server/app.js';

if (!process.env.PLAYWRIGHT_BROWSERS_PATH && existsSync('.browser-cache')) process.env.PLAYWRIGHT_BROWSERS_PATH = path.resolve('.browser-cache');
const { chromium, expect } = await import('@playwright/test');
let app;
const server = createServer((req, res) => app(req, res));
server.listen(0, '127.0.0.1');
await once(server, 'listening');
const origin = `http://127.0.0.1:${server.address().port}`;
app = createApp({ config: loadConfig({ NODE_ENV: 'test', APP_MODE: 'demo', APP_ORIGIN: origin }) });
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, permissions: ['clipboard-read', 'clipboard-write'], reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await mkdir('.impeccable/review', { recursive: true });
  await page.goto(origin);
  await expect(page.getByText('当前为演示模式', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '查询企业邮箱' })).toBeDisabled();
  await page.screenshot({ path: '.impeccable/review/empty.png', fullPage: true });
  await page.getByRole('button', { name: '填入示例' }).click();
  await page.getByRole('button', { name: '查询企业邮箱' }).click();
  const sample = 'lin.xiao@example.com chen.yu@example.com xu.yan@example.com';
  await expect(page.locator('#email-output')).toHaveValue(sample);
  await expect(page.getByText('1 项需要确认')).toBeVisible();
  await page.getByRole('button', { name: '复制邮箱', exact: true }).click();
  await expect(page.getByRole('button', { name: '已复制', exact: true })).toBeVisible();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), sample);
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile has horizontal overflow');
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.locator('#employee-numbers').fill('E1001\n\n E1001 \nMISSING\nE1003');
  await expect(page.locator('#email-output')).toHaveCount(0);
  await page.getByRole('button', { name: '查询企业邮箱' }).click();
  await expect(page.locator('#email-output')).toHaveValue('lin.xiao@example.com');
  await expect(page.getByText('2 项需要确认')).toBeVisible();
  await page.getByRole('tab', { name: '选择成员 / 部门' }).click();
  await page.getByRole('button', { name: '打开演示通讯录' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('checkbox', { name: '产品研发 部门' }).check();
  await page.getByRole('checkbox', { name: '林晓 E1001' }).check();
  await page.screenshot({ path: '.impeccable/review/picker.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.impeccable/review/picker-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '确认选择' }).click();
  await page.getByRole('button', { name: '查询企业邮箱' }).click();
  await expect(page.locator('#email-output')).toHaveValue(sample);
  await page.getByRole('checkbox', { name: '包含所选部门的全部子部门' }).uncheck();
  await expect(page.locator('#email-output')).toHaveCount(0);
  await page.getByRole('button', { name: '查询企业邮箱' }).click();
  await expect(page.locator('#email-output')).toHaveValue('lin.xiao@example.com');
  await page.getByRole('button', { name: '移除成员 林晓' }).click();
  await page.getByRole('button', { name: '查询企业邮箱' }).click();
  await expect(page.locator('#email-output')).toHaveValue('');
  await expect(page.getByRole('button', { name: '复制邮箱' })).toBeDisabled();
  await page.getByRole('tab', { name: '按工号查询' }).click();
  await page.locator('#employee-numbers').fill(Array.from({ length: 1001 }, (_, index) => `E${index}`).join('\n'));
  await expect(page.getByRole('button', { name: '查询企业邮箱' })).toBeDisabled();
  await page.locator('#employee-numbers').fill('E1001');
  await page.route('**/api/resolve/employee-numbers', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: { code: 'TEST', message: '测试网络异常，请重试。' } }) }));
  await page.getByRole('button', { name: '查询企业邮箱' }).click();
  await expect(page.getByRole('alert')).toContainText('测试网络异常');
  await page.screenshot({ path: '.impeccable/review/error-mobile.png', fullPage: true });
  await page.unroute('**/api/resolve/employee-numbers');
  assert.deepEqual(errors, [], 'browser runtime errors');
  console.log('UI smoke passed: empty, sample, dedupe, issues, copy, stale-result clearing, picker, descendants toggle, empty results, limit, error, desktop/mobile overflow.');
} finally {
  await browser?.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
}
